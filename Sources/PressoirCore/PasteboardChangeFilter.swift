/// What the pasteboard holds at one instant, read by the app adapter.
public struct PasteboardSnapshot: Equatable, Sendable {
    public let changeCount: Int
    public let text: String?
    public let types: Set<String>

    public init(changeCount: Int, text: String?, types: Set<String>) {
        self.changeCount = changeCount
        self.text = text
        self.types = types
    }
}

/// Decides whether a pasteboard snapshot is a new copy worth keeping. Password
/// managers and system tools tag their writes with the nspasteboard.org markers;
/// those are never kept, so a copied password never reaches the history file.
public struct PasteboardChangeFilter: Equatable, Sendable {
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public let lastChangeCount: Int

    public init(lastChangeCount: Int) {
        self.lastChangeCount = lastChangeCount
    }

    public func evaluate(_ snapshot: PasteboardSnapshot) -> (filter: PasteboardChangeFilter, captured: String?) {
        guard snapshot.changeCount != lastChangeCount else { return (self, nil) }
        let next = PasteboardChangeFilter(lastChangeCount: snapshot.changeCount)
        guard snapshot.types.isDisjoint(with: Self.ignoredTypes) else { return (next, nil) }
        return (next, snapshot.text)
    }
}
