/// What to read from the pasteboard after a change.
public enum CaptureKind: Equatable, Sendable {
    case text, image
}

/// Decides, from the pasteboard's change count, type list and the app in front,
/// whether a change is a new copy worth keeping and what to read, so that heavy
/// image data is only fetched when it will be kept.
///
/// Never kept: writes tagged with the nspasteboard.org markers (password managers,
/// system tools), copies made inside a known password manager, content arriving
/// from another Apple device, and Pressoir's own paste.
public struct PasteboardChangeFilter: Equatable, Sendable {
    /// Put on the pasteboard by Pressoir when it pastes an entry back.
    public static let ownPasteType = "io.github.toowame.Pressoir.paste"

    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard",
        ownPasteType,
    ]
    static let excludedSourceApps: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.dashlane.dashlanephonefinal",
        "in.sinew.Enpass-Desktop",
    ]
    static let textType = "public.utf8-plain-text"
    static let imageTypes: Set<String> = ["public.png", "public.tiff"]
    /// A Finder file copy also carries the file's icon as TIFF: not a picture copy.
    static let fileURLType = "public.file-url"

    public let lastChangeCount: Int

    public init(lastChangeCount: Int) {
        self.lastChangeCount = lastChangeCount
    }

    public func evaluate(changeCount: Int, types: Set<String>, sourceBundleId: String? = nil)
        -> (filter: PasteboardChangeFilter, kind: CaptureKind?)
    {
        guard changeCount != lastChangeCount else { return (self, nil) }
        let next = PasteboardChangeFilter(lastChangeCount: changeCount)
        guard sourceBundleId.map({ !Self.excludedSourceApps.contains($0) }) ?? true else { return (next, nil) }
        return (next, Self.kind(of: types))
    }

    private static func kind(of types: Set<String>) -> CaptureKind? {
        guard types.isDisjoint(with: ignoredTypes) else { return nil }
        if types.contains(textType) { return .text }
        if types.contains(fileURLType) { return nil }
        return types.isDisjoint(with: imageTypes) ? nil : .image
    }
}
